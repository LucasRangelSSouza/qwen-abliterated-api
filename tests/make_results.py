#!/usr/bin/env python3
"""Build docs/RESULTS.md from reports/*.json (quality, speed, long context, cost). Missing inputs are skipped, never invented.
usage: python tests/make_results.py > docs/RESULTS.md"""
import json, os, glob

R = "reports"
GPU_USD_H = 0.449


def load(name):
    p = os.path.join(R, name)
    return json.load(open(p, encoding="utf-8")) if os.path.exists(p) else None


def pct(a, b):
    return f"{a}/{b} ({100 * a / b:.1f}%)"


o = ["# Results\n", "Generated by `tests/make_results.py` from `reports/*.json`. Every number here is reproducible with the scripts in `tests/`.\n"]

# ---------------------------------------------------------------- quality
q = {"Sonnet 5 medium (yardstick, no tools)": load("quality-claude-sonnet-5-medium.json"),
     "Qwen3.8-27B abliterated FP8 + DFlash2": load("quality-fp8.json"),
     "Qwen3.8-27B abliterated NVFP4 + DFlash2": load("quality-nvfp4.json")}
o.append("## Quality (same prompts, same local grader)\n\nHumanEval: 164 problems, pass@1, greedy, code executed locally. GSM8K: first 200 test problems, exact match. Qwen runs with thinking off.\n")
o.append("| model | HumanEval | GSM8K | run time |\n|---|---:|---:|---:|")
for name, d in q.items():
    if d:
        o.append(f"| {name} | {pct(d['humaneval']['passed'], d['humaneval']['total'])} | {pct(d['gsm8k']['passed'], d['gsm8k']['total'])} | {d['seconds']} s |")
    else:
        o.append(f"| {name} | pending | pending | |")
o.append("")

# ---------------------------------------------------------------- speed
r_nv, r_fp = load("run-2.json"), load("run-fp8-160k.json")
if r_nv and r_fp:
    o.append("## Speed (through the public HTTPS endpoint)\n\nNVFP4 was measured at max_model_len 32 768 (run-2), FP8 at 160 000 (run-fp8-160k); single runs per cell, so differences of a few tok/s are within noise (the FP8 2-client aggregate of 22 tok/s is a warm-up outlier).\n\n| workload | thinking | NVFP4 tok/s | FP8 tok/s |\n|---|---|---:|---:|")
    for k, v in r_nv["sections"]["speed"].items():
        w = r_fp["sections"]["speed"].get(k)
        name, think = k.split("_think=")
        o.append(f"| {name} | {'on' if think == 'True' else 'off'} | {v['decode_tps']['mean']} | {w['decode_tps']['mean'] if w else '-'} |")
    o.append("\n| clients | NVFP4 aggregate tok/s | FP8 aggregate tok/s |\n|---|---:|---:|")
    for k, v in r_nv["sections"]["concurrency"].items():
        w = r_fp["sections"]["concurrency"].get(k)
        o.append(f"| {k[2:]} | {v['aggregate_tps']} | {w['aggregate_tps'] if w else '-'} |")
    o.append("")

# ---------------------------------------------------------------- long context
lc = {"NVFP4": load("longctx-nvfp4-160k.json"), "FP8": load("longctx-fp8-160k.json")}
if all(lc.values()):
    o.append("## Long context (needle in a haystack, max_model_len 160 000, bf16 KV cache)\n\n| prompt tokens (approx.) | NVFP4 found | NVFP4 TTFT | FP8 found | FP8 TTFT |\n|---|---:|---:|---:|---:|")
    sizes = sorted({r["target"] for r in lc["NVFP4"]})
    for s in sizes:
        cells = []
        for m in ("NVFP4", "FP8"):
            rows = [r for r in lc[m] if r["target"] == s]
            cells += [f"{sum(r['ok'] for r in rows)}/{len(rows)}", f"{sum(r['ttft'] for r in rows) / len(rows):.0f} s"]
        pt = round(sum(r["prompt_tokens"] for r in lc["FP8"] if r["target"] == s) / max(1, len([r for r in lc["FP8"] if r["target"] == s])) / 1000)
        o.append(f"| ~{pt}k | " + " | ".join(cells) + " |")
    o.append("\nWith the fp8 KV cache instead, needles were lost from ~22k tokens (12 of 36 attempts, garbage output). See `reports/longctx-kv-auto.json` and the run-1 log.\n")

# ---------------------------------------------------------------- cost
c = q["Sonnet 5 medium (yardstick, no tools)"]
o.append("## Cost per task\n\nGPU: US$ %.3f/h rented, 4 parallel requests, cost = run seconds x price. Claude: `total_cost_usd` reported by Claude Code (API-equivalent).\n" % GPU_USD_H)
o.append("| model | tasks | cost | per 1000 tasks |\n|---|---:|---:|---:|")
if c:
    n = c["humaneval"]["total"] + c["gsm8k"]["total"]
    cost = c["usage"]["cost"]
    o.append(f"| Sonnet 5 medium | {n} | US$ {cost:.2f} | US$ {1000 * cost / n:.2f} |")
for name in ("FP8", "NVFP4"):
    d = q[f"Qwen3.8-27B abliterated {name} + DFlash2"]
    if d:
        n = d["humaneval"]["total"] + d["gsm8k"]["total"]
        cost = d["seconds"] * GPU_USD_H / 3600
        o.append(f"| Qwen {name} (busy GPU) | {n} | US$ {cost:.2f} | US$ {1000 * cost / n:.2f} |")
if c:
    per_task_claude = c["usage"]["cost"] / (c["humaneval"]["total"] + c["gsm8k"]["total"])
    f8 = q["Qwen3.8-27B abliterated FP8 + DFlash2"]
    lines = ["", f"Break-even: one GPU-hour (US$ {GPU_USD_H}) buys the same as ~{GPU_USD_H / per_task_claude:.0f} Claude tasks of this size."]
    if f8:
        tph = 3600 * (f8["humaneval"]["total"] + f8["gsm8k"]["total"]) / f8["seconds"]
        lines.append(f"A saturated GPU does ~{tph:.0f} such tasks/hour, so renting wins above ~{GPU_USD_H / per_task_claude / tph * 100:.0f}% utilisation of one instance and loses below it. An idle rented GPU costs the same per hour.")
    lines.append("Claude's figure is API-equivalent cost reported by Claude Code; on a subscription the marginal cost is different.\n")
    o.append("\n".join(lines))

print("\n".join(o))
