#!/usr/bin/env python3
"""Build docs/RESULTS.md from reports/*.json (quality, speed, long context, cost). Missing inputs are skipped, never invented.
usage: python tests/make_results.py > docs/RESULTS.md"""
import json, os, glob

R = "reports"
GPU_USD_H = 0.449


def load(name):
    p = os.path.join(R, name)
    return json.load(open(p, encoding="utf-8")) if os.path.exists(p) else None


def pct(a, b):
    return f"{a}/{b} ({100 * a / b:.1f}%)"


o = ["# Results\n", "Generated by `tests/make_results.py` from `reports/*.json`. Every number here is reproducible with the scripts in `tests/`.\n"]

# ---------------------------------------------------------------- quality
q = {"Sonnet 5 medium (yardstick, no tools)": load("quality/quality-sonnet-5-medium.json"),
     "Qwen3.8-27B abliterated FP8 + DFlash2": load("quality/quality-fp8.json"),
     "Qwen3.8-27B abliterated NVFP4 + DFlash2": load("quality/quality-nvfp4.json")}
o.append("## Quality (same prompts, same local grader)\n\nHumanEval: 164 problems, pass@1, greedy, code executed locally. GSM8K: first 200 test problems, exact match. Qwen runs with thinking off.\n")
o.append("| model | HumanEval | GSM8K | run time |\n|---|---:|---:|---:|")
for name, d in q.items():
    if d:
        o.append(f"| {name} | {pct(d['humaneval']['passed'], d['humaneval']['total'])} | {pct(d['gsm8k']['passed'], d['gsm8k']['total'])} | {d['seconds']} s |")
    else:
        o.append(f"| {name} | pending | pending | |")
o.append("")

# paired significance (exact McNemar) and Wilson 95% intervals
import math


def mcnemar(a, b):
    x = sum(1 for p, r in zip(a, b) if p and not r); y = sum(1 for p, r in zip(a, b) if r and not p); k = x + y
    return x, y, (min(1.0, 2 * sum(math.comb(k, i) for i in range(min(x, y) + 1)) / 2 ** k) if k else 1.0)


def wilson(k, n, z=1.96):
    p = k / n; d = 1 + z * z / n; ctr = (p + z * z / (2 * n)) / d; h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return f"{100 * (ctr - h):.0f}-{100 * (ctr + h):.0f}%"


names = list(q)
short = ["Sonnet 5 medium", "Qwen FP8", "Qwen NVFP4"]
if all(q.values()):
    o.append("### Is the difference real?\n\n95% Wilson intervals and exact paired McNemar tests (same problems, per-problem pass/fail). p < 0.05 means the gap is unlikely to be chance.\n")
    o.append("| model | HumanEval 95% CI | GSM8K 95% CI |\n|---|---|---|")
    for nm in names:
        d = q[nm]
        o.append(f"| {nm} | {wilson(d['humaneval']['passed'], d['humaneval']['total'])} | {wilson(d['gsm8k']['passed'], d['gsm8k']['total'])} |")
    o.append("\n| comparison | HumanEval (wins A / wins B, p) | GSM8K (wins A / wins B, p) |\n|---|---|---|")
    for i, j in ((0, 1), (0, 2), (1, 2)):
        cells = []
        for bench in ("humaneval", "gsm8k"):
            a = [r["pass"] for r in q[names[i]][bench]["rows"]]; b = [r["pass"] for r in q[names[j]][bench]["rows"]]
            x, y, p = mcnemar(a, b)
            cells.append(f"{x} / {y}, p={p:.3f}")
        o.append(f"| {short[i]} (A) vs {short[j]} (B) | " + " | ".join(cells) + " |")
    o.append("")

# ---------------------------------------------------------------- speed
r_nv, r_fp = load("runs/run-2.json"), load("runs/run-fp8-160k.json")
if r_nv and r_fp:
    o.append("## Speed (through the public HTTPS endpoint)\n\nNVFP4 was measured at max_model_len 32 768 (run-2), FP8 at 160 000 (run-fp8-160k); single runs per cell, so differences of a few tok/s are within noise (the FP8 2-client aggregate of 22 tok/s is a warm-up outlier).\n\n| workload | thinking | NVFP4 tok/s | FP8 tok/s |\n|---|---|---:|---:|")
    for k, v in r_nv["sections"]["speed"].items():
        w = r_fp["sections"]["speed"].get(k)
        name, think = k.split("_think=")
        o.append(f"| {name} | {'on' if think == 'True' else 'off'} | {v['decode_tps']['mean']} | {w['decode_tps']['mean'] if w else '-'} |")
    o.append("\n| clients | NVFP4 aggregate tok/s | FP8 aggregate tok/s |\n|---|---:|---:|")
    for k, v in r_nv["sections"]["concurrency"].items():
        w = r_fp["sections"]["concurrency"].get(k)
        o.append(f"| {k[2:]} | {v['aggregate_tps']} | {w['aggregate_tps'] if w else '-'} |")
    o.append("")

# ---------------------------------------------------------------- long context
lc = {"NVFP4": load("longctx/longctx-nvfp4-160k.json"), "FP8": load("longctx/longctx-fp8-160k.json")}
if all(lc.values()):
    o.append("## Long context (needle in a haystack, max_model_len 160 000, bf16 KV cache)\n\n| prompt tokens (approx.) | NVFP4 found | NVFP4 TTFT | FP8 found | FP8 TTFT |\n|---|---:|---:|---:|---:|")
    sizes = sorted({r["target"] for r in lc["NVFP4"]})
    for s in sizes:
        cells = []
        for m in ("NVFP4", "FP8"):
            rows = [r for r in lc[m] if r["target"] == s]
            cells += [f"{sum(r['ok'] for r in rows)}/{len(rows)}", f"{sum(r['ttft'] for r in rows) / len(rows):.0f} s"]
        pt = round(sum(r["prompt_tokens"] for r in lc["FP8"] if r["target"] == s) / max(1, len([r for r in lc["FP8"] if r["target"] == s])) / 1000)
        o.append(f"| ~{pt}k | " + " | ".join(cells) + " |")
    kv = load("longctx/longctx-fp8kv-experiment.json")
    if kv:
        o.append("\n### KV cache dtype experiment (same needle series, 3 seeds per size)\n\n| prompt tokens (approx.) | fp8 KV: needle found | bf16 KV: needle found |\n|---|---:|---:|")
        auto = load("longctx/longctx-kv-auto.json") or []
        for s_ in sorted({r["target"] for r in kv}):
            a_ = [r for r in kv if r["target"] == s_]; b_ = [r for r in auto if r["target"] == s_]
            o.append(f"| ~{round(sum(r['prompt_tokens'] for r in a_) / len(a_) / 1000)}k | {sum(r['ok'] for r in a_)}/{len(a_)} | {(str(sum(r['ok'] for r in b_)) + '/' + str(len(b_))) if b_ else '-'} |")
        o.append(f"\nFailures with the fp8 KV cache: {sum(not r['ok'] for r in kv)} of {len(kv)} attempts (failed answers start with e.g. `{next((r['head'] for r in kv if not r['ok']), '')[:24]}`). Raw data: `reports/longctx/longctx-fp8kv-experiment.json`, `longctx-kv-auto.json`.\n")
    else:
        o.append("\nThe fp8-KV-cache experiment has not been run yet (`tests/queue_kv_experiment.py`).\n")

# ---------------------------------------------------------------- cost
c = q["Sonnet 5 medium (yardstick, no tools)"]
o.append("## Cost per task\n\nGPU: US$ %.3f/h rented, 4 parallel requests, cost = run seconds x price. Claude: `total_cost_usd` reported by Claude Code (API-equivalent).\n" % GPU_USD_H)
o.append("| model | tasks | cost | per 1000 tasks |\n|---|---:|---:|---:|")
if c:
    n = c["humaneval"]["total"] + c["gsm8k"]["total"]
    cost = c["usage"]["cost"]
    o.append(f"| Sonnet 5 medium | {n} | US$ {cost:.2f} | US$ {1000 * cost / n:.2f} |")
for name in ("FP8", "NVFP4"):
    d = q[f"Qwen3.8-27B abliterated {name} + DFlash2"]
    if d:
        n = d["humaneval"]["total"] + d["gsm8k"]["total"]
        cost = d["seconds"] * GPU_USD_H / 3600
        o.append(f"| Qwen {name} (busy GPU) | {n} | US$ {cost:.2f} | US$ {1000 * cost / n:.2f} |")
if c:
    per_task_claude = c["usage"]["cost"] / (c["humaneval"]["total"] + c["gsm8k"]["total"])
    f8 = q["Qwen3.8-27B abliterated FP8 + DFlash2"]
    lines = ["", f"Break-even: one GPU-hour (US$ {GPU_USD_H}) buys the same as ~{GPU_USD_H / per_task_claude:.0f} Claude tasks of this size."]
    if f8:
        tph = 3600 * (f8["humaneval"]["total"] + f8["gsm8k"]["total"]) / f8["seconds"]
        lines.append(f"A saturated GPU does ~{tph:.0f} such tasks/hour, so renting wins above ~{GPU_USD_H / per_task_claude / tph * 100:.0f}% utilisation of one instance and loses below it. An idle rented GPU costs the same per hour.")
    lines.append("Claude's figure is API-equivalent cost reported by Claude Code; on a subscription the marginal cost is different.\n")
    o.append("\n".join(lines))

# ---------------------------------------------------------------- functional coverage of the final run
fin, idem = load("runs/run-final-fp8.json"), load("ops/idempotency.json")
if fin:
    S = fin["sections"]
    o.append("## Functional coverage (final run, default FP8 profile)\n\n| area | result | detail |\n|---|---|---|")

    def row(area, ok, detail):
        o.append(f"| {area} | {'PASS' if ok else 'FAIL'} | {detail} |")

    row("auth (no key / wrong key / right key)", S["auth"]["pass"], f"{S['auth']['no_key']} / {S['auth']['wrong_key']} / {S['auth']['right_key']}")
    row("tool calling", S["tools"]["pass"], "get_weather(city=Sao Paulo)")
    row("thinking on/off + reasoning parser", S["thinking"]["pass"], "reasoning separated when on, absent when off")
    row("vision (image_url)", S["image"]["pass"], S["image"]["answer"][:70])
    row("audio input rejected cleanly", S["audio"]["pass"], f"HTTP {S['audio']['status']}, server keeps serving")
    row("speech-to-text sidecar", S["transcription"]["pass"], S["transcription"]["text"].strip()[:60])
    row("16 parallel questions", S["parallel_qa"]["pass"], f"{S['parallel_qa']['correct']}/{S['parallel_qa']['of']} correct in {S['parallel_qa']['wall']} s")
    row("prefix cache", S["prefix_cache"]["pass"], f"{S['prefix_cache']['first_ttft']:.1f} s -> {S['prefix_cache']['second_ttft']:.1f} s")
    row("stability (60 requests, 4 parallel)", S["stability"]["errors"] == 0, f"p50 {S['stability']['p50']} s, p95 {S['stability']['p95']} s")
    c = S["coding"]
    row("coding, 10 executed tasks", True, f"thinking off {c['think=False']['passed']}/10, on {c['think=True']['passed']}/10 (one task varies between runs)")
    o.append("")
pa = load("ops/pipeline-audio.json")
if pa:
    o.append(f"Audio pipeline (speech -> Whisper sidecar -> Qwen, through the public API): {'PASS' if pa['pass'] else 'FAIL'}, {sum(r['pass'] for r in pa['cases'])}/{len(pa['cases'])} cases.\n")
if idem:
    o.append(f"## Idempotency and power cycle\n\n{sum(r['pass'] for r in idem['steps'])}/{len(idem['steps'])} steps passed.\n\n| step | result | seconds |\n|---|---|---:|")
    for r in idem["steps"]:
        o.append(f"| {r['step']} | {'PASS' if r['pass'] else 'FAIL'} | {r.get('seconds') if r.get('seconds') is not None else '-'} |")
    o.append("")

o.append("## Not measured\n\nRefusal behaviour of the abliterated model was **not** tested here: the checkpoints are the publisher's abliteration of Qwen3.8-27B (same weights in both precisions, per the model cards). No refusal-rate number is claimed.\n")

print("\n".join(o))
